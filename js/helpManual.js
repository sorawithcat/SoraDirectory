function buildHelpNavHtml() {
    return '<details class="sora-help-chapters" data-sora-details="true" data-default-open="false"><summary>手册章节</summary><div class="sora-details-body"><ul>' +
        SORA_HELP_CHAPTERS.map(chapter => `<li><a href="sora-dir:${chapter.id}" data-sora-link="dir" data-dir-id="${chapter.id}">${escapeHtml(chapter.title)}</a></li>`).join('') + '</ul></div></details>';
}

