function openHelpManual() {
    const rows = buildHelpManualMulufile();
    const wrapper = document.createElement('div'); wrapper.className = 'sora-help';
    const nav = document.createElement('nav'); nav.className = 'sora-help-sidebar'; nav.setAttribute('aria-label', '使用说明章节');
    const search = document.createElement('input'); search.type = 'search'; search.placeholder = '搜索操作、格式或问题'; search.setAttribute('aria-label', '搜索使用说明');
    const chapterSelect = document.createElement('select'); chapterSelect.className = 'sora-help-chapter-select'; chapterSelect.setAttribute('aria-label', '选择说明章节');
    rows.forEach(row => chapterSelect.append(new Option(row[1], row[2])));
    const searchStatus = document.createElement('p'); searchStatus.className = 'sora-help-search-status'; searchStatus.setAttribute('role', 'status'); searchStatus.hidden = true;
    const clearSearch = document.createElement('button'); clearSearch.type = 'button'; clearSearch.className = 'sora-help-clear'; clearSearch.textContent = '清除搜索'; clearSearch.hidden = true;
    const links = document.createElement('div'); links.className = 'sora-help-links';
    const reader = document.createElement('section'); reader.className = 'sora-help-reader';
    const outlineLabel = document.createElement('label'); outlineLabel.className = 'sora-help-outline'; outlineLabel.append('本章小节');
    const outline = document.createElement('select'); outlineLabel.append(outline);
    const article = document.createElement('article'); article.className = 'markdown-preview sora-help-content'; article.tabIndex = 0;
    const pager = document.createElement('nav'); pager.className = 'sora-help-pager'; pager.setAttribute('aria-label', '说明翻页');
    const previous = document.createElement('button'), next = document.createElement('button'), position = document.createElement('span');
    previous.type = next.type = 'button'; position.className = 'sora-help-position'; pager.append(previous, position, next);
    const announce = document.createElement('span'); announce.className = 'sora-help-sr-only'; announce.setAttribute('role', 'status');
    let activeIndex = 0;
    const matches = new Map();
    const buttons = new Map();
    const searchIndex = rows.map(row => {
        const source = document.createElement('template'); source.innerHTML = row[3];
        source.content.querySelector('.sora-help-chapters')?.remove();
        return Array.from(source.content.querySelectorAll('.sora-manual-section')).map(section => ({
            anchor: section.querySelector('h2[id]')?.id || '',
            text: section.textContent.replace(/\s+/g, ' ').trim()
        }));
    });

    function scrollToSection(anchor) {
        const target = article.querySelector(`[id="${CSS.escape(anchor)}"]`);
        if (!target) return;
        for (let node = target.parentElement; node && node !== article; node = node.parentElement) {
            if (node.tagName === 'DETAILS') node.open = true;
        }
        article.scrollTop += target.getBoundingClientRect().top - article.getBoundingClientRect().top - 16;
    }
    function open(id, anchor = '', fromSearch = false) {
        activeIndex = Math.max(0, rows.findIndex(row => row[2] === id));
        const row = rows[activeIndex];
        article.innerHTML = sanitizeEditorHtml(row[3]);
        article.querySelector('.sora-help-chapters')?.remove();
        SoraContentFormats.normalizeCallouts(article);
        SoraContentFormats.normalizeFootnotes(article);
        article.querySelectorAll('input[type="checkbox"]').forEach(input => { input.disabled = true; });
        article.setAttribute('aria-label', row[1]);
        if (fromSearch && search.value.trim()) {
            const term = search.value.trim().toLocaleLowerCase();
            article.querySelectorAll('details').forEach(detail => { if (detail.textContent.toLocaleLowerCase().includes(term)) detail.open = true; });
        }
        outline.replaceChildren(new Option('回到本章开头', ''));
        article.querySelectorAll('h2[id],h3[id]').forEach(heading => outline.append(new Option(heading.textContent, heading.id)));
        buttons.forEach((button, chapterId) => {
            if (chapterId === row[2]) button.setAttribute('aria-current', 'page');
            else button.removeAttribute('aria-current');
        });
        chapterSelect.value = row[2];
        previous.disabled = activeIndex === 0; next.disabled = activeIndex === rows.length - 1;
        previous.textContent = activeIndex ? `上一章 · ${rows[activeIndex - 1][1]}` : '已是第一章';
        next.textContent = activeIndex < rows.length - 1 ? `下一章 · ${rows[activeIndex + 1][1]}` : '已是最后一章';
        position.textContent = `${activeIndex + 1} / ${rows.length}`;
        announce.textContent = `当前章节：${row[1]}`;
        article.scrollTop = 0;
        if (anchor) { scrollToSection(anchor); if (Array.from(outline.options).some(option => option.value === anchor)) outline.value = anchor; }
    }

    [...new Set(SORA_HELP_CHAPTERS.map(chapter => chapter.group))].forEach(group => {
        const section = document.createElement('section'); section.className = 'sora-help-nav-group';
        const heading = document.createElement('h3'); heading.textContent = group; section.append(heading);
        SORA_HELP_CHAPTERS.filter(chapter => chapter.group === group).forEach(chapter => {
            const button = document.createElement('button'); button.type = 'button'; button.className = 'sora-help-chapter';
            const title = document.createElement('span'); title.textContent = chapter.title;
            const excerpt = document.createElement('small'); excerpt.className = 'sora-help-excerpt'; excerpt.hidden = true;
            button.append(title, excerpt); button.onclick = () => open(chapter.id, matches.get(chapter.id)?.anchor || '', !!search.value.trim());
            buttons.set(chapter.id, button); section.append(button);
        });
        links.append(section);
    });
    function filterChapters() {
        const term = search.value.trim().toLocaleLowerCase();
        matches.clear();
        rows.forEach((row, index) => {
            const titleMatch = `${row[1]} ${SORA_HELP_CHAPTERS[index].summary}`.toLocaleLowerCase().includes(term);
            const segment = searchIndex[index].find(item => item.text.toLocaleLowerCase().includes(term));
            const matched = !term || titleMatch || !!segment;
            const button = buttons.get(row[2]); button.hidden = !matched;
            const excerpt = button.querySelector('small'); excerpt.hidden = !term || !matched;
            if (matched) {
                matches.set(row[2], { anchor: titleMatch ? '' : segment?.anchor || '' });
                const text = titleMatch ? SORA_HELP_CHAPTERS[index].summary : segment?.text || '';
                const start = Math.max(0, text.toLocaleLowerCase().indexOf(term) - 16);
                excerpt.textContent = `${start ? '…' : ''}${text.slice(start, start + 72)}${text.length > start + 72 ? '…' : ''}`;
            }
        });
        links.querySelectorAll('.sora-help-nav-group').forEach(group => { group.hidden = !group.querySelector('button:not([hidden])'); });
        wrapper.dataset.searching = String(!!term);
        searchStatus.hidden = clearSearch.hidden = !term;
        searchStatus.textContent = matches.size ? `找到 ${matches.size} 个章节，点击可定位相关小节。` : '没有找到相关内容，试试“表格”“草稿”或“部署”。';
    }
    search.oninput = filterChapters;
    clearSearch.onclick = () => { search.value = ''; filterChapters(); search.focus(); };
    chapterSelect.onchange = () => { open(chapterSelect.value); article.focus({ preventScroll: true }); };
    outline.onchange = () => { if (outline.value) scrollToSection(outline.value); else article.scrollTop = 0; };
    previous.onclick = () => { if (activeIndex > 0) { open(rows[activeIndex - 1][2]); article.focus({ preventScroll: true }); } };
    next.onclick = () => { if (activeIndex < rows.length - 1) { open(rows[activeIndex + 1][2]); article.focus({ preventScroll: true }); } };
    article.addEventListener('click', event => {
        const target = event.target.closest('a[href]');
        if (!target) return;
        const href = target.getAttribute('href');
        if (!href.startsWith('sora-dir:') && !href.startsWith('#')) return;
        event.preventDefault(); event.stopPropagation();
        if (href.startsWith('#')) scrollToSection(href.slice(1));
        else { const [id, anchor] = href.slice(9).split('#'); open(id, anchor || ''); }
    });
    nav.append(search, chapterSelect, searchStatus, clearSearch, links);
    reader.append(outlineLabel, article, pager, announce); wrapper.append(nav, reader);
    FeatureDialog.open('使用说明', wrapper);
    open(rows[0][2]);
}
